    static get(iconName, size = 24) {
        const icon = this.icons[iconName];
        if (!icon) return '';
        return icon.replace(/width="\d+"/g, `width="${size}"`).replace(/height="\d+"/g, `height="${size}"`);
    }
    
    static replaceAllEmojis() {
        document.querySelectorAll('[data-icon]').forEach(el => {
            const iconName = el.dataset.icon;
            const size = el.dataset.iconSize || 24;
            el.innerHTML = IconSystem.get(iconName, size);
        });
    }

    static initObserver() {
        this.replaceAllEmojis();
        const observer = new MutationObserver((mutations) => {
            let shouldReplace = false;
            for (const m of mutations) {
                if (m.addedNodes.length > 0) {
                    for (const node of m.addedNodes) {
                        if (node.nodeType === Node.ELEMENT_NODE && (node.hasAttribute('data-icon') || (node.querySelector && node.querySelector('[data-icon]')))) {
                            shouldReplace = true;
                            break;
                        }
                    }
                }
                if (shouldReplace) break;
            }
            if (shouldReplace) this.replaceAllEmojis();
        });
        if (document.body) {
            observer.observe(document.body, { childList: true, subtree: true });
        }
    }
